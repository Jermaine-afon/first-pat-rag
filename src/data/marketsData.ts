// Helper to generate realistic historical OHLC data for charts
export function generateHistory(basePrice: number, points: number = 30, volatility: number = 0.015) {
  const data = [];
  let currentPrice = basePrice * (1 - volatility * 3);
  const now = new Date();
  
  for (let i = points; i >= 0; i--) {
    const timestamp = new Date(now.getTime() - i * 3600 * 1000 * 4);
    const change = (Math.random() - 0.48) * volatility * currentPrice;
    const open = currentPrice;
    currentPrice = Math.max(0.1, currentPrice + change);
    const close = currentPrice;
    const high = Math.max(open, close) + Math.random() * (volatility * 0.5 * currentPrice);
    const low = Math.min(open, close) - Math.random() * (volatility * 0.5 * currentPrice);
    const volume = Math.floor(Math.random() * 500000 + 100000);
    
    data.push({
      time: timestamp.toLocaleDateString('en-US', { month: 'short', day: 'numeric', hour: '2-digit' }),
      price: Number(close.toFixed(2)),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume
    });
  }
  return data;
}

